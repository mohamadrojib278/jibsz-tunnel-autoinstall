# 2. Pengecekan OS & Arsitektur (Ubuntu 22.04 LTS / Debian 12 x86_64)
check_os_arch() {
    local arch
    arch=$(uname -m)
    if [[ "$arch" != "x86_64" ]]; then
        log_err "Arsitektur sistem Anda ($arch) tidak didukung. Wajib x86_64 (amd64)."
        exit 1
    fi

    if [[ ! -f /etc/os-release ]]; then
        log_err "File /etc/os-release tidak ditemukan. OS tidak dikenali."
        exit 1
    fi

    # shellcheck disable=SC1091
    source /etc/os-release
    local os_id="${ID,,}"
    local os_ver="${VERSION_ID}"

    if [[ "$os_id" == "ubuntu" ]]; then
        if [[ "$os_ver" != "22.04" && "$os_ver" != "24.04" && "$os_ver" != "20.04" ]]; then
            log_warn "Terdeteksi Ubuntu ${os_ver}. Proyek dioptimalkan untuk Ubuntu 22.04 LTS."
        else
            log_ok "OS Terdeteksi: ${PRETTY_NAME} (${arch})"
        fi
    elif [[ "$os_id" == "debian" ]]; then
        if [[ "$os_ver" != "12" && "$os_ver" != "11" ]]; then
            log_warn "Terdeteksi Debian ${os_ver}. Proyek dioptimalkan untuk Debian 12 (Bookworm)."
        else
            log_ok "OS Terdeteksi: ${PRETTY_NAME} (${arch})"
        fi
    else
        log_err "OS ${PRETTY_NAME} tidak didukung! Gunakan Ubuntu 22.04 LTS atau Debian 12."
        exit 1
    fi
}

# 3. Perbaikan DNS /etc/resolv.conf ke 1.1.1.1 & 8.8.8.8
fix_dns_resolver() {
    log_info "Mengonfigurasi DNS Resolver (/etc/resolv.conf) ke Cloudflare (1.1.1.1) & Google (8.8.8.8)..."
    if systemctl is-active --quiet systemd-resolved 2>/dev/null; then
        systemctl stop systemd-resolved 2>/dev/null || true
        systemctl disable systemd-resolved 2>/dev/null || true
    fi

    if [[ -L /etc/resolv.conf ]]; then
        rm -f /etc/resolv.conf
    fi

    chattr -i /etc/resolv.conf 2>/dev/null || true
    cat << 'EOF' > /etc/resolv.conf
# Generated by Jibsz Tunneling AutoInstaller (@admj1btnl)
nameserver 1.1.1.1
nameserver 8.8.8.8
nameserver 1.0.0.1
nameserver 8.8.4.4
options timeout:2 attempts:3 rotate
EOF
    log_ok "DNS /etc/resolv.conf berhasil dikunci ke 1.1.1.1 & 8.8.8.8."
}

# 4. Input Interaktif Custom Port Web Panel & Kredensial Admin
prompt_user_inputs() {
    echo -e "${C_PURPLE}────────────────────────────────────────────────────────────────────────${C_RESET}"
    echo -e "${C_WHITE} Konfigurasi Awal Web Panel Installer (Jibsz Tunneling / J1BTNL)${C_RESET}"
    echo -e "${C_PURPLE}────────────────────────────────────────────────────────────────────────${C_RESET}"

    while [[ -z "$CUSTOM_PORT" ]]; do
        read -rp "Masukkan Custom Port Web Panel [default: 8080, contoh NAT: 2052/10250]: " input_port
        input_port="${input_port:-8080}"
        if [[ "$input_port" =~ ^[0-9]+$ ]] && (( input_port >= 81 && input_port <= 65535 )) && (( input_port != 443 )); then
            CUSTOM_PORT="$input_port"
        else
            log_warn "Port harus berupa angka antara 81-65535 dan tidak boleh menggunakan port 80 atau 443."
        fi
    done

    while [[ -z "$ADMIN_USER" ]]; do
        read -rp "Masukkan Username Admin Web Panel [default: admin]: " input_user
        ADMIN_USER="${input_user:-admin}"
    done

    while [[ -z "$ADMIN_PASS" ]]; do
        read -rsp "Masukkan Password Admin Web Panel [default: jibsz123]: " input_pass
        echo ""
        ADMIN_PASS="${input_pass:-jibsz123}"
    done

    log_ok "Port Web Panel : ${CUSTOM_PORT}"
    log_ok "Username Admin : ${ADMIN_USER}"
}

