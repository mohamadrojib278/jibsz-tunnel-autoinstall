set -e

C_RESET="\033[0m"
C_CYAN="\033[1;36m"
C_PURPLE="\033[1;35m"
C_GREEN="\033[1;32m"
C_YELLOW="\033[1;33m"
C_RED="\033[1;31m"
C_WHITE="\033[1;37m"

INSTALL_DIR="/opt/jibsz-tunnel"
CONFIG_DIR="/etc/jibsz"
LOG_DIR="/var/log/jibsz"
DB_FILE="${CONFIG_DIR}/jibsz.db"
REPO_GIT_URL="https://github.com/mohamadrojib278/jibsz-tunnel-autoinstall.git"

CUSTOM_PORT=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --port|-p)
            CUSTOM_PORT="$2"
            shift 2
            ;;
        *)
            shift
            ;;
    esac
done

print_banner() {
    clear
    echo -e "${C_PURPLE}╔══════════════════════════════════════════════════════════════════════╗${C_RESET}"
    echo -e "${C_PURPLE}║${C_CYAN}        JIBSZ TUNNELING / J1BTNL - AUTOSCRIPT & WEB INSTALLER        ${C_PURPLE}║${C_RESET}"
    echo -e "${C_PURPLE}║${C_WHITE}         Multi-Protokol: SSH WS • VMess • VLESS • Trojan             ${C_PURPLE}║${C_RESET}"
    echo -e "${C_PURPLE}║${C_YELLOW}     Support: VPS IP Public & VPS NAT (Cloudflare Zero Trust)        ${C_PURPLE}║${C_RESET}"
    echo -e "${C_PURPLE}║${C_GREEN}         Credit: @admj1btnl | github.com/mohamadrojib278              ${C_PURPLE}║${C_RESET}"
    echo -e "${C_PURPLE}╚══════════════════════════════════════════════════════════════════════╝${C_RESET}"
    echo ""
}

log_info() { echo -e "${C_CYAN}[INFO]${C_RESET} $1"; }
log_ok()   { echo -e "${C_GREEN}[OK]${C_RESET} $1"; }
log_warn() { echo -e "${C_YELLOW}[WARN]${C_RESET} $1"; }
log_err()  { echo -e "${C_RED}[ERROR]${C_RESET} $1"; }

check_root() {
    if [[ $EUID -ne 0 ]]; then
        log_err "Script ini wajib dijalankan sebagai user root! Gunakan: sudo bash setup.sh"
        exit 1
    fi
}

check_os_arch() {
    local arch
    arch=$(uname -m)
    if [[ "$arch" != "x86_64" ]]; then
        log_err "Arsitektur sistem Anda ($arch) tidak didukung. Wajib x86_64 (amd64)."
        exit 1
    fi
    if [[ -f /etc/os-release ]]; then
        # shellcheck disable=SC1091
        source /etc/os-release
        log_ok "OS Terdeteksi: ${PRETTY_NAME} (${arch})"
    fi
}

fix_dns_resolver() {
    log_info "Mengonfigurasi DNS Resolver (/etc/resolv.conf) ke Cloudflare (1.1.1.1) & Google (8.8.8.8)..."
    if systemctl is-active --quiet systemd-resolved 2>/dev/null; then
        systemctl stop systemd-resolved 2>/dev/null || true
        systemctl disable systemd-resolved 2>/dev/null || true
    fi

    if [[ -L /etc/resolv.conf ]]; then
        rm -f /etc/resolv.conf
    fi

    chattr -i /etc/resolv.conf 2>/dev/null || true
    cat << 'EOF' > /etc/resolv.conf
# Generated by Jibsz Tunneling AutoInstaller (@admj1btnl)
nameserver 1.1.1.1
nameserver 8.8.8.8
nameserver 1.0.0.1
nameserver 8.8.4.4
options timeout:2 attempts:3 rotate
EOF
    log_ok "DNS /etc/resolv.conf berhasil dikunci ke 1.1.1.1 & 8.8.8.8."
}

prompt_user_inputs() {
    if [[ -z "$CUSTOM_PORT" && -f "${DB_FILE}" ]]; then
        local existing_port
        existing_port=$(sqlite3 "${DB_FILE}" "SELECT value FROM settings WHERE key='panel_port' LIMIT 1;" 2>/dev/null || echo "")
        if [[ -n "$existing_port" ]]; then
            echo -e "${C_PURPLE}────────────────────────────────────────────────────────────────────────${C_RESET}"
            read -rp "Masukkan Custom Port Web Panel [Enter untuk tetap di port ${existing_port}]: " input_port
            CUSTOM_PORT="${input_port:-$existing_port}"
            log_ok "Port Web Panel : ${CUSTOM_PORT}"
            return
        fi
    fi

    echo -e "${C_PURPLE}────────────────────────────────────────────────────────────────────────${C_RESET}"
    echo -e "${C_WHITE} Konfigurasi Awal Port Web Panel (Akses Publik Tanpa Login)${C_RESET}"
    echo -e "${C_PURPLE}────────────────────────────────────────────────────────────────────────${C_RESET}"

    while [[ -z "$CUSTOM_PORT" ]]; do
        read -rp "Masukkan Custom Port Web Panel [default: 8080, contoh NAT: 2052/10250]: " input_port
        input_port="${input_port:-8080}"
        if [[ "$input_port" =~ ^[0-9]+$ ]] && (( input_port >= 81 && input_port <= 65535 )) && (( input_port != 443 )); then
            CUSTOM_PORT="$input_port"
        else
            log_warn "Port harus berupa angka antara 81-65535 dan tidak boleh menggunakan port 80 atau 443."
        fi
    done

    log_ok "Port Web Panel : ${CUSTOM_PORT}"
}

install_base_dependencies() {
    log_info "Memperbarui repositori APT dan memastikan paket dasar Python 3 & SQLite3 tersedia..."
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y \
        python3 \
        python3-pip \
        python3-venv \
        sqlite3 \
        curl \
        wget \
        git \
        unzip \
        jq \
        openssl \
        ca-certificates \
        lsof \
        net-tools \
        procps \
        cron \
        tzdata

    timedatectl set-timezone Asia/Jakarta 2>/dev/null || ln -sf /usr/share/zoneinfo/Asia/Jakarta /etc/localtime
    log_ok "Paket dasar dan timezone (Asia/Jakarta) siap."
}

deploy_project_files() {
    log_info "Menyiapkan direktori proyek di ${INSTALL_DIR} dan ${CONFIG_DIR}..."
    mkdir -p "${INSTALL_DIR}" "${CONFIG_DIR}" "${LOG_DIR}"
    chmod 777 "${LOG_DIR}" 2>/dev/null || true

    local script_dir
    script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

    if [[ -d "${script_dir}/backend" && -d "${script_dir}/webpanel" && -d "${script_dir}/cli" ]]; then
        log_info "Menyalin file proyek dari direktori lokal (${script_dir})..."
        cp -rf "${script_dir}/backend" "${INSTALL_DIR}/"
        cp -rf "${script_dir}/webpanel" "${INSTALL_DIR}/"
        cp -rf "${script_dir}/cli" "${INSTALL_DIR}/"
        cp -f "${script_dir}/README.md" "${INSTALL_DIR}/" 2>/dev/null || true
        cp -f "${script_dir}/setup.sh" "${INSTALL_DIR}/" 2>/dev/null || true
    else
        log_info "Mengunduh repositori proyek dari GitHub (${REPO_GIT_URL})..."
        rm -rf /tmp/jibsz-clone
        if git clone --depth 1 "${REPO_GIT_URL}" /tmp/jibsz-clone; then
            cp -rf /tmp/jibsz-clone/* "${INSTALL_DIR}/"
            rm -rf /tmp/jibsz-clone
        else
            log_err "Gagal meng-clone repositori GitHub. Pastikan koneksi internet aktif atau jalankan dari folder ekstrak ZIP."
            exit 1
        fi
    fi

    chmod +x "${INSTALL_DIR}/backend/installer_engine.sh"
    chmod +x "${INSTALL_DIR}/backend/ssh_ws_proxy.py"
    chmod +x "${INSTALL_DIR}/cli/"*.sh

    ln -sf "${INSTALL_DIR}/cli/menu.sh" /usr/local/bin/menu
    ln -sf "${INSTALL_DIR}/cli/menu.sh" /usr/local/bin/jibsz
    ln -sf "${INSTALL_DIR}/cli/manage_ssh.sh" /usr/local/bin/menu-ssh
    ln -sf "${INSTALL_DIR}/cli/manage_xray.sh" /usr/local/bin/menu-vmess
    ln -sf "${INSTALL_DIR}/cli/manage_xray.sh" /usr/local/bin/menu-vless
    ln -sf "${INSTALL_DIR}/cli/manage_xray.sh" /usr/local/bin/menu-trojan
    ln -sf "${INSTALL_DIR}/cli/menu.sh" /usr/local/bin/menu-system

    log_ok "Seluruh file proyek dan symlink perintah CLI berhasil dipasang."
}

setup_python_and_database() {
    log_info "Menyiapkan Python Virtual Environment di ${INSTALL_DIR}/venv..."
    if [[ ! -d "${INSTALL_DIR}/venv" ]]; then
        python3 -m venv "${INSTALL_DIR}/venv"
    fi

    "${INSTALL_DIR}/venv/bin/pip" install --upgrade pip
    "${INSTALL_DIR}/venv/bin/pip" install -r "${INSTALL_DIR}/webpanel/requirements.txt"

    log_info "Menginisialisasi database SQLite (${DB_FILE})..."
    local pub_ip
    pub_ip=$(curl -s4 --max-time 5 https://icanhazip.com || curl -s4 --max-time 5 https://ifconfig.me || hostname -I | awk '{print $1}')
    pub_ip=$(echo "$pub_ip" | tr -d '[:space:]')

    sqlite3 "${DB_FILE}" <<EOF
PRAGMA journal_mode=WAL;

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS component_status (
    component_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    message TEXT DEFAULT 'Menunggu proses instalasi...',
    updated_at TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS accounts (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    protocol TEXT NOT NULL,
    username TEXT UNIQUE NOT NULL,
    secret TEXT NOT NULL,
    exp_timestamp INTEGER NOT NULL,
    exp_display TEXT NOT NULL,
    is_trial INTEGER DEFAULT 0,
    ip_limit INTEGER DEFAULT 2,
    quota_gb REAL DEFAULT 0,
    up_bytes INTEGER DEFAULT 0,
    down_bytes INTEGER DEFAULT 0,
    status TEXT DEFAULT 'active',
    created_at TEXT DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS active_ips (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    username TEXT NOT NULL,
    protocol TEXT NOT NULL,
    client_ip TEXT NOT NULL,
    last_seen INTEGER NOT NULL,
    UNIQUE(username, protocol, client_ip)
);

INSERT OR REPLACE INTO settings (key, value) VALUES ('panel_port', '${CUSTOM_PORT}');
INSERT OR REPLACE INTO settings (key, value) VALUES ('public_ip', '${pub_ip}');
INSERT OR IGNORE INTO settings (key, value) VALUES ('install_mode', 'unconfigured');
INSERT OR IGNORE INTO settings (key, value) VALUES ('domain', '');
INSERT OR IGNORE INTO settings (key, value) VALUES ('acme_email', 'admin@j1btnl.local');
INSERT OR IGNORE INTO settings (key, value) VALUES ('cf_token', '');
INSERT OR IGNORE INTO settings (key, value) VALUES ('is_installed', '0');

INSERT OR IGNORE INTO component_status (component_id, name, status, message) VALUES
('nginx', 'Dependency & Nginx Reverse Proxy (localhost:80)', 'pending', 'Menunggu instalasi'),
('tunnel_ssl', 'Cloudflare Tunnel (cloudflared) / SSL Certificate', 'pending', 'Menunggu instalasi'),
('ssh', 'SSH Tunneling (OpenSSH, Dropbear, SSH WS Proxy & BadVPN UDPGW)', 'pending', 'Menunggu instalasi'),
('vless', 'VLESS (Xray-core WS & gRPC)', 'pending', 'Menunggu instalasi'),
('vmess', 'VMess (Xray-core WS & gRPC)', 'pending', 'Menunggu instalasi'),
('trojan', 'Trojan (Xray-core WS & gRPC)', 'pending', 'Menunggu instalasi');
EOF

    cat <<EOF > "${CONFIG_DIR}/panel.env"
PANEL_PORT=${CUSTOM_PORT}
DB_PATH=${DB_FILE}
INSTALL_DIR=${INSTALL_DIR}
CONFIG_DIR=${CONFIG_DIR}
LOG_DIR=${LOG_DIR}
EOF
    chmod 600 "${CONFIG_DIR}/panel.env"
    log_ok "Database SQLite dan konfigurasi panel siap."
}

sync_existing_installation_if_present() {
    local is_inst
    is_inst=$(sqlite3 "${DB_FILE}" "SELECT value FROM settings WHERE key='is_installed' LIMIT 1;" 2>/dev/null || echo "0")
    if [[ "$is_inst" == "1" || -f "${CONFIG_DIR}/installed.lock" ]]; then
        log_info "Mendeteksi instalasi aktif: Memperbarui konfigurasi Nginx & Xray (VLESS, VMess, Trojan)..."
        # Buka kembali akun yang sempat ter-lock secara keliru oleh versi lama
        sqlite3 "${DB_FILE}" "DELETE FROM active_ips; UPDATE accounts SET status='active' WHERE status='locked';" 2>/dev/null || true

        rm -rf /etc/systemd/system/xray.service.d
        cat << 'EOF' > /etc/systemd/system/xray.service
[Unit]
Description=Jibsz Xray-core Multi-Protocol Service (VMess, VLESS, Trojan + Stats API)
After=network.target nss-lookup.target

[Service]
Type=simple
User=root
ExecStart=/usr/local/bin/xray run -config /usr/local/etc/xray/config.json
Restart=on-failure
RestartSec=2
LimitNPROC=10000
LimitNOFILE=1000000

[Install]
WantedBy=multi-user.target
EOF
        systemctl daemon-reload 2>/dev/null || true

        "${INSTALL_DIR}/venv/bin/python3" -c "import sys; sys.path.insert(0, '${INSTALL_DIR}/webpanel'); import app; app.sync_nginx_config_if_installed(); app.sync_xray_accounts_to_config()" || true
        systemctl restart nginx xray ssh-ws 2>/dev/null || true
        log_ok "Konfigurasi Nginx & Xray berhasil diperbarui dan semua akun telah disinkronkan!"
    fi
}

setup_webpanel_service() {
    log_info "Mendaftarkan & me-restart service systemd jibsz-webpanel pada 0.0.0.0:${CUSTOM_PORT}..."

    cat <<EOF > /etc/systemd/system/jibsz-webpanel.service
[Unit]
Description=Jibsz Tunneling / J1BTNL Public Web Panel & Installer Service
After=network.target

[Service]
Type=simple
User=root
WorkingDirectory=${INSTALL_DIR}/webpanel
EnvironmentFile=${CONFIG_DIR}/panel.env
ExecStart=${INSTALL_DIR}/venv/bin/uvicorn app:app --host 0.0.0.0 --port ${CUSTOM_PORT} --workers 1
Restart=always
RestartSec=3
StandardOutput=append:${LOG_DIR}/webpanel.log
StandardError=append:${LOG_DIR}/webpanel.log

[Install]
WantedBy=multi-user.target
EOF

    if pidof systemd >/dev/null 2>&1; then
        systemctl daemon-reload
        systemctl enable jibsz-webpanel >/dev/null 2>&1 || true
        systemctl restart jibsz-webpanel
    else
        pkill -f "uvicorn app:app" 2>/dev/null || true
        nohup "${INSTALL_DIR}/venv/bin/uvicorn" app:app --app-dir "${INSTALL_DIR}/webpanel" --host 0.0.0.0 --port "${CUSTOM_PORT}" >> "${LOG_DIR}/webpanel.log" 2>&1 &
    fi

    if command -v ufw >/dev/null 2>&1 && ufw status | grep -q "Status: active"; then
        ufw allow "${CUSTOM_PORT}/tcp" >/dev/null 2>&1 || true
    fi
    iptables -I INPUT -p tcp --dport "${CUSTOM_PORT}" -j ACCEPT 2>/dev/null || true

    sleep 2
    log_ok "Service jibsz-webpanel telah aktif di 0.0.0.0:${CUSTOM_PORT}."
}

